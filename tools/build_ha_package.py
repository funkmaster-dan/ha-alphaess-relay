#!/usr/bin/env python3
"""Assemble the self-contained HA component from the tested relay core.

No runtime pip package, external process, firmware or private capture is needed.
--check detects generated-source drift without changing any files.
"""
import argparse
import hashlib
import json
from pathlib import Path
import zipfile

ROOT = Path(__file__).resolve().parents[1]
COMPONENT = ROOT / "custom_components/alphaess_relay"
SOURCES = {"relay.py": "alpha_relay/relay.py", "observer.py": "alpha_relay/observer.py",
           "standalone.py": "alpha_relay/standalone.py",
           "payload.py": "tools/alpha_payload.py"}


def sync(check=False):
    target = COMPONENT / "_relay"
    expected = {"__init__.py": b'"""Bundled relay core, generated by tools/build_ha_package.py."""\n'}
    provenance = {}
    for name, source in SOURCES.items():
        data = (ROOT / source).read_bytes()
        provenance[name] = {"source": source, "sha256": hashlib.sha256(data).hexdigest()}
        data = data.replace(b"from tools.alpha_payload import", b"from .payload import")
        expected[name] = b"# Generated from " + source.encode() + b"; edit the canonical source.\n" + data
    expected["sources.json"] = (json.dumps(provenance, indent=2, sort_keys=True)+"\n").encode()
    if not check:
        target.mkdir(exist_ok=True)
    for name, data in expected.items():
        path = target / name
        if check:
            if not path.exists() or path.read_bytes() != data:
                raise SystemExit("Bundled core differs: run tools/build_ha_package.py")
        else:
            path.write_bytes(data)
    return provenance


def package():
    destination = ROOT / "dist"
    destination.mkdir(exist_ok=True)
    manifest = json.loads((COMPONENT / "manifest.json").read_text())
    path = destination / f"alphaess-relay-{manifest['version']}.zip"
    files = [(p.relative_to(ROOT).as_posix(), p) for p in COMPONENT.rglob("*")
             if p.is_file() and p.suffix in (".py", ".json", ".md", ".png")
             and "__pycache__" not in p.parts]
    files.extend([("hacs.json", ROOT/"hacs.json"), ("README.md", COMPONENT/"README.md"),
                  ("STANDALONE.md", ROOT/"STANDALONE.md")])
    with zipfile.ZipFile(path, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for name, source in sorted(files):
            info = zipfile.ZipInfo(name, date_time=(2026, 10, 20, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o100644 << 16
            archive.writestr(info, source.read_bytes())
    print(json.dumps({"archive": str(path.relative_to(ROOT)), "files": len(files),
                      "sha256": hashlib.sha256(path.read_bytes()).hexdigest()}))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--sync-only", action="store_true")
    args = parser.parse_args()
    sync(args.check)
    if args.check:
        print("Bundled relay core matches canonical tested sources")
    elif not args.sync_only:
        package()
